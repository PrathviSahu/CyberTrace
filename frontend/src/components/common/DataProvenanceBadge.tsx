import React from "react";
import { DataProvenance } from "../../types";

interface DataProvenanceBadgeProps {
  provenance: DataProvenance | string;
  size?: "sm" | "md";
}

export const DataProvenanceBadge: React.FC<DataProvenanceBadgeProps> = ({
  provenance,
  size = "sm",
}) => {
  const norm = (provenance || "unknown").toLowerCase().trim();
  const isEvaluation = norm === "calculated_evaluation";
  const isBenchmark =
    norm === "synthetic_benchmark" ||
    norm === "demo_benchmark" ||
    norm === "simulated_attack" ||
    norm === "synthetic";
  const isObserved = norm === "observed_telemetry" || norm === "live_telemetry";
  const isMixed = norm === "mixed";

  const sizeClass = size === "sm" ? "text-[11px] px-2 py-0.5" : "text-xs px-2.5 py-0.5";

  if (isEvaluation) {
    return (
      <span
        title="Formally calculated across benchmark scenarios"
        className={`inline-flex items-center gap-1.5 font-sans font-medium text-[#6EA59A] bg-[#6EA59A]/10 border border-[#6EA59A]/25 rounded-md ${sizeClass}`}
      >
        <span className="w-1.5 h-1.5 rounded-full bg-[#6EA59A] shrink-0" />
        Calculated Evaluation
      </span>
    );
  }

  if (isBenchmark) {
    return (
      <span
        title="Generated by ThreatLab or synthetic benchmark generator"
        className={`inline-flex items-center gap-1.5 font-sans font-medium text-[#9B8FA8] bg-[#9B8FA8]/10 border border-[#9B8FA8]/25 rounded-md ${sizeClass}`}
      >
        <span className="w-1.5 h-1.5 rounded-full bg-[#9B8FA8] shrink-0" />
        Synthetic Benchmark
      </span>
    );
  }

  if (isMixed) {
    return (
      <span
        title="Results contain events with multiple distinct provenance classifications"
        className={`inline-flex items-center gap-1.5 font-sans font-medium text-[#D99A54] bg-[#D99A54]/10 border border-[#D99A54]/25 rounded-md ${sizeClass}`}
      >
        <span className="w-1.5 h-1.5 rounded-full bg-[#D99A54] shrink-0" />
        Mixed Provenance
      </span>
    );
  }

  if (isObserved) {
    return (
      <span
        title="Imported from an identified, authorized telemetry source with verified source attribution"
        className={`inline-flex items-center gap-1.5 font-sans font-medium text-[#B58A61] bg-[#B58A61]/10 border border-[#B58A61]/25 rounded-md ${sizeClass}`}
      >
        <span className="w-1.5 h-1.5 rounded-full bg-[#B58A61] shrink-0" />
        Observed Telemetry
      </span>
    );
  }

  // Explicit Fallback for Unknown / Unverified Provenance
  return (
    <span
      title="Source provenance cannot be verified from available metadata"
      className={`inline-flex items-center gap-1.5 font-sans font-medium text-[#A0A7AE] bg-[#24282C] border border-[#30363C] rounded-md ${sizeClass}`}
    >
      <span className="w-1.5 h-1.5 rounded-full bg-[#737D87] shrink-0" />
      Unknown Provenance
    </span>
  );
};
